import { chromium } from '@playwright/test';
const B = process.argv[2] ?? 'http://localhost:3100';
const browser = await chromium.launch();
let fails = 0;
const ok = (c, l) => { if (!c) fails++; console.log(c ? '  ok  ' : '  FAIL', l); };
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addInitScript(() => localStorage.setItem('train-tracker:theme', 'light'));
const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(`${B}/trains`, { waitUntil: 'domcontentloaded' });
await p.getByLabel('From', { exact: true }).fill('chennai');
const first = await p.getByRole('option').first().innerText();
ok(/Chennai.*all stations/i.test(first), `typing a city offers "all stations" first: ${first.split('\n')[0]}`);
ok(/MAS/.test(first), 'it lists the stations it will search');
await p.getByRole('option').first().click();
await p.getByLabel('To', { exact: true }).fill('trivandrum');
await p.getByRole('option').filter({ hasText: /\(TVC\)|TVC/ }).first().click();
await p.getByRole('button', { name: 'Search trains' }).click();
await p.waitForURL(/from=~MAS|from=%7EMAS/);
await p.waitForSelector('article', { timeout: 90000 });
const names = await p.locator('article h3').count();
ok(names >= 3, `trains found across the city (${names})`);
ok((await p.getByText('Boarding at').count()) > 0, 'station filter chips appear');
const body = await p.locator('body').innerText();
ok(/Chennai \(all stations\)/.test(body), 'header shows the city name, not a code');
ok(errs.length === 0, `no page errors ${errs.join('|').slice(0, 100)}`);
// a plain station name must not trigger the city row
await p.goto(`${B}/trains`, { waitUntil: 'domcontentloaded' });
await p.getByLabel('From', { exact: true }).fill('kanpur central');
const k = await p.getByRole('option').first().innerText();
ok(!/all stations/i.test(k), `a single station name stays a single station: ${k.split('\n')[0]}`);
await browser.close();
console.log(fails ? `${fails} FAILED` : 'ALL CHECKS PASSED');
process.exit(fails ? 1 : 0);
